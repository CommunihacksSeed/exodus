/**
 * Writes docs/REVIEW.md: every published sentence next to the passage it rests on,
 * so a person can check meaning (the build only checks that quotes are verbatim).
 * Run after `npm run data`.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import type { Claim, PublishedItem, VerifiedCitation } from '../src/types.ts'

const items: PublishedItem[] = JSON.parse(readFileSync(new URL('../src/generated/items.json', import.meta.url), 'utf8'))

const SECTIONS = [
  ['whatIsProposed', 'What is being proposed?'],
  ['why', 'Why?'],
  ['whoIsAffected', 'Who does it affect?'],
  ['conditionsAndUnknowns', 'Conditions and things not settled'],
  ['whatHappensNext', 'What happens next?'],
] as const

function claimLines(c: Claim<VerifiedCitation>): string[] {
  const out = [`- [ ] **${c.text}**`]
  if (c.caveat) out.push(`  - Keep in mind: ${c.caveat}`)
  for (const q of c.citations) {
    const where = `${q.sourceLabel}${q.page ? `, page ${q.page}` : ''}`
    out.push(`  - > “${q.quote}”`, `    — [${where}](${q.url})`)
  }
  return out
}

const out: string[] = [
  '# Human review sheet',
  '',
  'Generated by `npm run review-sheet`. Do not edit by hand.',
  '',
  'Software has confirmed that every quote below appears word for word in its source. It cannot',
  'tell whether a sentence says more than its quote supports. That is what this review is for.',
  '',
  'For each sentence, ask:',
  '',
  '1. Does the quote support everything the sentence says, including numbers and dates?',
  '2. Is the right body named? Staff advise, committees recommend, only Council decides.',
  '3. Has a condition been lost ("subject to", "and/or", "up to")?',
  '4. Would a resident act wrongly after reading it?',
  '',
  'To sign off an item, set `review.humanReviewedBy` and `review.reviewedOn` (YYYY-MM-DD) in its',
  'file under `data/explanations/`, then run `npm run data`. The page then shows who checked it.',
  '',
]

for (const { record, explanation: e } of items) {
  if (!e) continue
  out.push(`## ${record.id}: ${e.plainTitle}`, '')
  out.push(`- Official title: ${record.title}`)
  out.push(`- City page: ${record.sourceUrl}`)
  out.push(`- Location shown: ${e.location.label} (${e.location.geocodeSource})`)
  out.push(`- Signed off by: ${e.review.humanReviewedBy ?? '**nobody yet**'}${e.review.reviewedOn ? ` on ${e.review.reviewedOn}` : ''}`, '')

  for (const [key, title] of SECTIONS) {
    if (e[key].length === 0) continue
    out.push(`### ${title}`, '')
    for (const c of e[key]) out.push(...claimLines(c))
    out.push('')
  }

  out.push('### One-line summary of each step', '')
  for (const [kind, c] of Object.entries(e.stageSummaries)) {
    if (c) out.push(`*${kind}*`, '', ...claimLines(c), '')
  }

  if (e.participationCheck) {
    const p = e.participationCheck
    out.push('### Contact details shown under "Can I still have a say?"', '')
    out.push('These were read by hand from the City page below, not checked by software. Please open it and confirm.', '')
    out.push(`- [ ] ${p.contact.label}: ${p.contact.email ?? 'no email'}, ${p.contact.phone ?? 'no phone'}`)
    out.push(`  - Source: ${p.contact.sourceUrl} (checked ${p.checkedOn})`)
    out.push(`- [ ] Deadline shown: ${p.deadlineText ?? 'none (the page says the City does not state one)'}`, '')
  }
}

writeFileSync(new URL('../docs/REVIEW.md', import.meta.url), out.join('\n'))
console.log(`Wrote docs/REVIEW.md for ${items.filter((i) => i.explanation).length} items.`)
